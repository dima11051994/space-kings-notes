const { simulate, buy } = require("./sim.js");
const DB = 10e6;
const DEF = { ...buy(DB, { "Ракетная установка": .35, "Легкий лазер": .25, "Тяжёлый лазер": .1, "Пушка Гаусса": .2, "Плазменное орудие": .1 }),
              "Малый щитовой купол": 1, "Большой щитовой купол": 1 };
const FLEETS = {
  "Бомбардировщики": { "Бомбардировщик": 1 },
  "Линкоры": { "Линкор": 1 },
  "Крейсеры": { "Крейсер": 1 },
  "Уничтожители": { "Уничтожитель": 1 },
  "Линейные крейсеры": { "Линейный крейсер": 1 },
  "Бомб 70 + Линк 30": { "Бомбардировщик": .7, "Линкор": .3 },
  "Бомб 60 + Крейс 40": { "Бомбардировщик": .6, "Крейсер": .4 },
  "Бомб 50 + ЛИ 50 (мясо)": { "Бомбардировщик": .5, "Лёгкий истребитель": .5 },
  "Бомб 70 + Уничт 30": { "Бомбардировщик": .7, "Уничтожитель": .3 },
};
console.log("типичная оборона 10 млн: РУ 35%, ЛЛ 25%, ТЛ 10%, Гаусс 20%, Плазма 10% + купола");
for (const [n, f] of Object.entries(FLEETS)) {
  let out = "не пробивает даже при 8x";
  for (const k of [1, 1.5, 2, 3, 4, 6, 8]) {
    const r = simulate(buy(DB * k, f), DEF, 4);
    if (r.att >= 3) { out = `побеждает от ${k}x, теряет ${(r.attLoss / 1e6).toFixed(1)} млн (${Math.round(r.attLoss / (DB * k) * 100)}% флота), обломков ${(r.debris / 1e6).toFixed(1)} млн`; break; }
  }
  console.log(n.padEnd(24), out);
}
