const { simulate, buy } = require("./sim.js");
const DB = 10e6, AB = 30e6;
const DOMES = { "Малый щитовой купол": 1, "Большой щитовой купол": 1 };
const MIX = {
  "только РУ": { "Ракетная установка": 1 },
  "только ЛЛ": { "Легкий лазер": 1 },
  "РУ+ЛЛ 50/50": { "Ракетная установка": .5, "Легкий лазер": .5 },
  "РУ+ЛЛ+Гаусс 40/30/30": { "Ракетная установка": .4, "Легкий лазер": .3, "Пушка Гаусса": .3 },
  "РУ+ЛЛ+ТЛ+Гаусс+Плазма": { "Ракетная установка": .35, "Легкий лазер": .25, "Тяжёлый лазер": .1, "Пушка Гаусса": .2, "Плазменное орудие": .1 },
  "ЛЛ+Гаусс+Плазма 40/40/20": { "Легкий лазер": .4, "Пушка Гаусса": .4, "Плазменное орудие": .2 },
};
const FLEETS = {
  "Линкоры": { "Линкор": 1 },
  "Бомбардировщики": { "Бомбардировщик": 1 },
  "Уничтожители": { "Уничтожитель": 1 },
  "Линк+Бомб 50/50": { "Линкор": .5, "Бомбардировщик": .5 },
  "Крейсеры": { "Крейсер": 1 },
  "Звёзды смерти": { "Звезда смерти": 1 },
};
console.log(`оборона ${DB / 1e6} млн (+купола) против флота ${AB / 1e6} млн; ячейка: победитель из 4 и (потери флота / реальные потери обороны)`);
console.log("".padEnd(26), Object.keys(FLEETS).map(f => f.slice(0, 12).padStart(14)).join(""));
for (const [dn, d] of Object.entries(MIX)) {
  const def = { ...buy(DB, d), ...DOMES };
  const cells = Object.values(FLEETS).map(f => {
    const r = simulate(buy(AB, f), def, 4);
    const w = r.def >= 3 ? "О" : r.att >= 3 ? "А" : "~";
    return `${w} ${(r.attLoss / Math.max(r.defLoss, 1)).toFixed(1)}`.padStart(14);
  });
  console.log(dn.padEnd(26), cells.join(""));
}
