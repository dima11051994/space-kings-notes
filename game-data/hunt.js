const { simulate, buy } = require("./sim.js");
const B = 10e6;
const HUNTERS = ["Лёгкий истребитель", "Тяжёлый истребитель", "Крейсер", "Линкор", "Бомбардировщик", "Уничтожитель", "Линейный крейсер"];
const PREY = {
  "рой ЛИ": { "Лёгкий истребитель": 1 },
  "крейсеры": { "Крейсер": 1 },
  "линкоры": { "Линкор": 1 },
  "бомбардир.": { "Бомбардировщик": 1 },
  "уничтож.": { "Уничтожитель": 1 },
  "лин.крейс.": { "Линейный крейсер": 1 },
  "смешанный": { "Лёгкий истребитель": .2, "Крейсер": .2, "Линкор": .3, "Линейный крейсер": .15, "Бомбардировщик": .15 },
  "транспорты": { "Большой транспорт": .5, "Мега-транспорт": .5 },
};
console.log(`флот-охотник ${B / 1e6} млн против флота-цели ${B / 1e6} млн; ячейка: победитель (А — охотник) и потери цели / потери охотника`);
console.log("".padEnd(20), Object.keys(PREY).map(p => p.padStart(11)).join(""));
for (const h of HUNTERS) {
  const cells = Object.values(PREY).map(p => {
    const r = simulate(buy(B, { [h]: 1 }), buy(B, p), 4);
    const w = r.att >= 3 ? "А" : r.def >= 3 ? "Ц" : "~";
    const ratio = r.defLoss / Math.max(r.attLoss, 1);
    return `${w} ${ratio > 99 ? ">99" : ratio.toFixed(1)}`.padStart(11);
  });
  console.log(h.padEnd(20), cells.join(""));
}
